// Get all cities for a region
export const getCitiesByRegion = (region: string): string[] => {
  const found = NZ_REGIONS.find(r => r.region === region);
  return found ? found.areas.map(a => a.city) : [];
};

// Get all suburbs for a city within a region
export const getSuburbsByCity = (region: string, city: string): string[] => {
  const regionData = NZ_REGIONS.find(r => r.region === region);
  if (!regionData) return [];
  const cityData = regionData.areas.find(a => a.city === city);
  return cityData ? cityData.suburbs : [];
};

// Legacy function for backward compatibility - returns cities (areas)
export const getAreasByRegion = (region: string): string[] => {
  return getCitiesByRegion(region);
};

// Get all regions
export const getAllRegions = (): string[] => {
  return NZ_REGIONS.map(r => r.region);
};

// Find the region for a given city
export const getRegionByCity = (city: string): string | null => {
  for (const region of NZ_REGIONS) {
    const found = region.areas.find(a => a.city === city);
    if (found) {
      return region.region;
    }
  }
  return null;
};